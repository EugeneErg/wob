// Кто спрашивает про режим и кто не спрашивает.
//
// Правило одно: вниз наследуется только спидран. Начал спидран истории —
// главы и уровни внутри уже спидранятся, и спрашивать их незачем: игрок
// начал одно состязание, а не набор отдельных.
//
// Обычное прохождение вниз не наследуется. Внутри него можно взяться
// спидранить отдельную главу или отдельный уровень — это законное
// самостоятельное состязание со своим временем, и отказ спидранить историю
// не должен его запрещать.
//
// Правило живёт здесь, а не в трёх экранах: в экранах его нельзя проверить
// тестом, а ошибка в нём выглядит безобидно (лишний или пропущенный вопрос),
// но ломает смысл записей — попытка окажется не тем состязанием, за которое
// себя выдаёт.

export const SCOPES = ['story', 'chapter', 'level']

// Ниже ли scope, чем тот, где начат спидран
const below = (scope, from) => SCOPES.indexOf(scope) > SCOPES.indexOf(from)

// Спрашивать ли режим, входя в scope, когда спидран начат на srScope
// (null — не начат).
export function shouldAsk(scope, srScope) {
  if (!srScope) return true              // спидран не идёт — выбор за игроком
  return !below(scope, srScope) && scope !== srScope
}

// Идёт ли спидран на этом уровне вложенности
export function inheritsSpeedrun(scope, srScope) {
  if (!srScope) return false
  return scope === srScope || below(scope, srScope)
}

// Какой вид записи получится, если начать спидран на этом уровне
export const kindOfScope = (scope) => scope
