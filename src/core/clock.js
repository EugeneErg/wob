// Фиксированный тик симуляции.
//
// Раньше World.step(dt) получал живой dt каждого кадра — на 240 Гц мониторе
// шаги мельче, на слабом телефоне крупнее и реже. Physics внутри себя уже
// давно считает на фиксированном подшаге (solver.js, this.fixed = 1/120),
// но сам вызов world.step() приходил с гуляющим dt, а вместе с ним — таймеры
// AI, спавн частиц, всё, что сущности считают в update(dt). Один и тот же
// уровень с одним и тем же вводом на разных FPS доходил до разных состояний.
//
// TICK_RATE — частота шагов игровой логики. Она не связана с частотой
// физического подшага (та своя, внутри Physics) и не обязана совпадать
// с частотой кадров экрана: рендер может быть 30, 60, 144 Гц — не важно,
// сколько тиков симуляции произошло за секунду, всегда одно и то же число
// (пока часы игрока не остановлены паузой).
export const TICK_RATE = 60
export const TICK_DT = 1 / TICK_RATE

// Аккумулятор превращает произвольный dt рендера в целое число тиков
// фиксированной длины — тот же приём, что и в Physics.step, только этажом
// выше, на уровне World. Если кадр слишком долгий (вкладка была свёрнута,
// лежала пауза загрузки и т.п.), лишнее время отбрасывается — иначе после
// возврата в игру был бы шквал из сотен тиков разом.
const MAX_FRAME = 0.25       // дольше этого куска времени за кадр не бывает
const MAX_TICKS_PER_FRAME = 8 // не более стольки тиков досчитываем за раз

export class FixedClock {
  constructor(rate = TICK_RATE) {
    this.dt = 1 / rate
    this._acc = 0
    this.tick = 0            // номер следующего тика, который будет сделан
  }

  // Сколько целых тиков нужно сделать для куска реального времени elapsed.
  // Вызывающая сторона сама вызывает onTick(tickIndex) нужное число раз —
  // так и запись ввода, и рендер видят один и тот же счётчик тиков.
  advance(elapsed, onTick) {
    this._acc = Math.min(this._acc + elapsed, MAX_FRAME)
    let n = 0
    while (this._acc >= this.dt && n < MAX_TICKS_PER_FRAME) {
      onTick(this.tick)
      this.tick++
      this._acc -= this.dt
      n++
    }
    if (n === MAX_TICKS_PER_FRAME) this._acc = 0
    return n
  }

  // Доля пути до следующего тика — на интерполяцию рендера между двумя
  // последними состояниями физики, если она когда-нибудь понадобится.
  get alpha() { return this._acc / this.dt }

  reset() { this._acc = 0; this.tick = 0 }
}
