// Очередь записи: каждая правка уезжает на сервер сама.
//
// Предыдущий вариант отправлял историю целиком по кнопке «Save», и это было
// неверно по одной причине: всё, что до кнопки, жило только в браузере.
// Закрытая вкладка, вычищенное хранилище, сломанный ноутбук — и вечер работы
// исчезает. Теперь на сервер уходит каждый элемент в момент изменения.
//
// Очередь, а не прямые вызовы, из-за трёх вещей, каждая из которых иначе теряет
// труд:
//
//   - порядок. Создание уровня и его сохранение — две записи, и вторая без
//     первой бессмысленна. Параллельные запросы приходят вразнобой;
//   - обрыв связи. Неудавшаяся запись остаётся в очереди и повторяется, а не
//     пропадает вместе с правкой;
//   - перезагрузка. Очередь лежит в localStorage, поэтому закрытая на середине
//     отправки вкладка ничего не уносит с собой.
//
// Версии историй сервер проверяет на каждой записи, поэтому очередь ещё и
// последовательная по необходимости: две одновременные правки одной истории
// гарантированно получили бы конфликт.

import { api, ApiError } from './api.js'

const KEY = 'goo.queue.v1'
// Остаток прежнего хранения версий: подчищается при выходе, чтобы не оставлять
// в браузере мусор от снятого решения.
const VERSIONS = 'goo.storyver.v1'

/**
 * Что происходит с очередью.
 *
 * Обычный объект, а не реактивный: очередь — модуль ядра, и тащить сюда Vue
 * значило бы затянуть UI-фреймворк в то, что обязано работать в голом Node.
 * Реактивность добавляет тот, кому она нужна, — обёрткой на стороне
 * компонента.
 */
export const queueState = {
  pending: 0,
  saving: false,
  // 'ok' | 'offline' | 'conflict' — что показать автору. Молчать здесь нельзя:
  // человек, уверенный, что работа сохранена, узнает обратное в худший момент.
  status: 'ok',
  error: null,
}

// Кто хочет знать об изменениях.
//
// Подписка, а не реактивный объект: очередь — модуль ядра и обязана работать в
// голом Node, а реактивность нужна только интерфейсу. Пусть он её и добавляет.
const listeners = new Set()

export function onQueueChange(fn) {
  listeners.add(fn)

  return () => listeners.delete(fn)
}

function announce() {
  for (const fn of listeners) fn({ ...queueState })
}

const read = (key, fallback) => {
  try {
    return JSON.parse(localStorage.getItem(key)) ?? fallback
  } catch {
    return fallback
  }
}

const write = (key, value) => {
  try {
    localStorage.setItem(key, JSON.stringify(value))
  } catch {
    // Хранилище переполнено. Правка всё равно уже в памяти и уедет, если
    // очередь доживёт до отправки.
  }
}

let queue = read(KEY, [])
queueState.pending = queue.length

/*
 * Версий черновика больше нет.
 *
 * Здесь жили versionOf/noteVersion/noteVersions — счётчик, который клиент был
 * обязан носить с собой и угадывать. Он защищал от двух рук, сохраняющих карту
 * главы целиком, но карта целиком и была неверной единицей записи. Мелкие
 * операции не спорят, так что защищать нечего.
 */

/**
 * Поставить запись в очередь.
 *
 * Возвращается сразу: редактор не должен ждать сеть, чтобы нарисовать то, что
 * автор уже сделал. Ответственность очереди — довезти.
 */
/*
 * Замка «один писатель за раз» здесь больше нет.
 *
 * Он появился, когда прямые записи и очередь гонялись за одну версию истории:
 * пока летело отложенное сохранение карты, нажатие «+» успевало прочитать
 * версию, очередь её сдвигала — и создание уровня получало 409. Замок это
 * лечил, но лечил симптом.
 *
 * Версий у черновика не стало, и гонке не за что цепляться: правки идут по
 * одному объекту, разные не пересекаются, одна и та же сходится к последней.
 * Замок пережил свою причину и держал очередь в очереди без надобности.
 */

export function enqueue(op) {
  const fresh = { ...op, id: `${Date.now()}-${Math.random().toString(36).slice(2, 8)}` }

  // Повторная запись того же целиком заменяет предыдущую, ещё не уехавшую.
  //
  // Карта главы и содержимое уровня отправляются целиком, а не приращениями,
  // поэтому из двух записей подряд ранняя не значит ничего: её результат
  // полностью перекрыт поздней. Пока очередь стояла, каждое движение мыши
  // добавляло в неё ещё один полный снимок карты, и разбор завала потом занимал
  // столько запросов, сколько было кадров.
  //
  // Голову очереди не трогаем: она может быть уже в полёте, и подменить ей
  // тело значит отправить одно, а записать в историю другое.
  const replaceable = fresh.method === 'put'
  const at = replaceable
    ? queue.findIndex((o, i) => i > 0 && o.method === 'put' && o.path === fresh.path)
    : -1

  if (at > 0) queue[at] = { ...fresh, id: queue[at].id }
  else queue.push(fresh)

  write(KEY, queue)
  queueState.pending = queue.length
  announce()
  drain()
}

let draining = false

/*
 * Конфликт останавливает очередь до отдельного решения человека.
 *
 * Раньше он только выставлял статус и выходил, не убрав запись, — а drain()
 * зовётся из enqueue(), из «вкладка снова видима», из «сеть ожила» и при
 * загрузке модуля. Застрявшая запись повторялась на каждое из этих событий, то
 * есть в редакторе — на каждое движение мыши, и переживала перезагрузку
 * страницы вместе с очередью. Со стороны это выглядело как поток одинаковых
 * 409, который нечем прекратить.
 */
let blocked = false

async function drain() {
  if (blocked || draining || queue.length === 0) return

  draining = true
  queueState.saving = true

  try {
    while (queue.length > 0) {
      const op = queue[0]

      try {
        await send(op)
      } catch (e) {
        if (e instanceof ApiError && e.status === 409) {
          // История изменилась в другом месте. Дальше слать бессмысленно:
          // каждая следующая запись получит тот же отказ, а автор рискует
          // затереть чужую работу вслепую.
          //
          // Принять версию сервера и повторить было бы соблазнительно и
          // неверно: это ровно та «последняя запись побеждает», от которой
          // версии и заведены. Решает человек, поэтому очередь встаёт до retry().
          blocked = true
          queueState.status = 'conflict'
          queueState.error = 'Эта история изменилась в другом месте. Обновите страницу, прежде чем править дальше.'
          announce()

          return
        }

        // Отказ, который не пройдёт никогда: уровня нет, доступа нет, тело не
        // принято. Повторять такое бессмысленно — правка застревает первой в
        // очереди и блокирует все, что за ней, повторяясь каждые две секунды до
        // конца сессии. Ровно это и случалось с уровнем, созданным в панели, но
        // не отправленным на сервер: PUT по несуществующему id, 404, и так по
        // кругу.
        //
        // Такую правку выкидываем и идём дальше, а автору говорим вслух: она
        // потеряна, и молчать об этом — худшее из возможного.
        if (e instanceof ApiError && e.status >= 400 && e.status < 500) {
          queue.shift()
          write(KEY, queue)
          queueState.pending = queue.length
          queueState.status = 'offline'
          queueState.error = `Не сохранилось: ${e.message}`
          announce()
          setTimeout(drain, 0)

          return
        }

        // Сеть или сервер. Ничего не выбрасываем: правка остаётся первой в
        // очереди и уйдёт при следующей попытке.
        queueState.status = 'offline'
        queueState.error = e.message
        announce()
        setTimeout(drain, 2000)

        return
      }

      queue.shift()
      write(KEY, queue)
      queueState.pending = queue.length
      announce()
    }

    queueState.status = 'ok'
    queueState.error = null
    announce()
  } finally {
    draining = false
    queueState.saving = queue.length > 0
    announce()
  }
}

async function send(op) {
  // Версия — свойство истории: она защищает от того, что двое правят одну
  // Версии в теле нет.
  //
  // Она защищала от двух рук, сохраняющих карту главы целиком, — но карта
  // целиком и была неверной единицей записи. Теперь черновик правится мелкими
  // операциями: разные точки не пересекаются, одна и та же сходится к
  // последней правке. Защищать нечего, а цена была высокой — отказы там, где
  // спора не бывает: создание уровня ничего не затирает, оно добавляет.
  await api[op.method](op.path, op.body)
}

/** Забыть очередь и версии — после выхода из аккаунта. */
export function forgetQueue() {
  queue = []
  write(KEY, queue)
  write(VERSIONS, {})
  blocked = false
  queueState.pending = 0
  queueState.status = 'ok'
  queueState.error = null
  announce()
}

/**
 * Отказаться от застрявшей правки.
 *
 * Единственный выход из конфликта, который ничего не затирает: то, что не
 * доехало, здесь и остаётся — зато очередь за ним снова идёт. Молчать об этом
 * нельзя, поэтому вызывающий говорит об отказе вслух.
 */
export function discardStuck() {
  queue.shift()
  write(KEY, queue)
  blocked = false
  queueState.pending = queue.length
  queueState.status = 'ok'
  queueState.error = null
  announce()
  drain()
}

/** Попробовать снова — после конфликта, когда автор перечитал историю. */
export function retry() {
  blocked = false
  queueState.status = 'ok'
  queueState.error = null
  drain()
}

// Вкладка вернулась в фокус или сеть ожила — самое время досылать.
if (typeof window !== 'undefined') {
  window.addEventListener('online', drain)
  document.addEventListener('visibilitychange', () => {
    if (!document.hidden) drain()
  })

  // Не гарантия, но лучше, чем ничего: если очередь непуста, предупредить.
  window.addEventListener('beforeunload', (e) => {
    if (queue.length === 0) return

    e.preventDefault()
    e.returnValue = ''
  })

  drain()
}
