// Слоты сохранений: несколько прохождений одной истории.
//
// Прогресс теперь принадлежит прохождению, а не игроку. Прежде он был плоской
// картой «уровень пройден», и второе прохождение начиналось уже пройденным —
// то есть не начиналось вовсе.
//
// Слоты живут только на сервере и только у авторизованных. Это не упущение:
// без аккаунта у игрока и историй-то почти нет — каталог отдаёт ему один
// уровень, — так что заводить для него полку сохранений не из чего.

import { api } from './api.js'

/** Прохождения этой истории, по номерам. */
export const slotsFor = (storyId) => api.get(`/api/stories/${storyId}/slots`)

/**
 * Начать новое прохождение.
 *
 * Номер выбирает сервер: он же знает, какие заняты, и он же решает, что их не
 * больше трёх. Клиенту незачем повторять это правило — повторённое, оно
 * однажды разойдётся с оригиналом.
 */
export const startSlot = (storyId) => api.post(`/api/stories/${storyId}/slots`)

export const renameSlot = (slotId, label) => api.patch(`/api/slots/${slotId}`, { label })

/** Начать это прохождение заново, не теряя места на полке. */
export const eraseSlot = (slotId) => api.post(`/api/slots/${slotId}/erase`)

export const deleteSlot = (slotId) => api.del(`/api/slots/${slotId}`)

/**
 * Перевести прохождение на другую версию истории.
 *
 * Отдельным действием и по решению игрока. Само по себе прохождение остаётся
 * на той версии, где началось: подменять контент под идущей игрой значит
 * двигать ворота посреди пути.
 */
export const moveSlotTo = (slotId, releaseId) => api.patch(`/api/slots/${slotId}`, { releaseId })
