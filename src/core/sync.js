// Что происходит при входе в аккаунт.
//
// Раньше здесь жило слияние: библиотека игрока лежала в localStorage, и вход
// означал «залить её на сервер, забрать чужое, свести прогресс». Всего этого
// больше нет, и не потому, что упростили, а потому, что исчезли причины.
//
// Содержимое теперь приходит из каталога — локальной библиотеки для игры не
// существует, сливать нечего. Прогресс принадлежит прохождению, а не игроку:
// его источник — выбранный слот, и вливать в него что-то со стороны значило бы
// начинать новое прохождение уже пройденным.
//
// Осталось ровно две обязанности: знать, есть ли с кем разговаривать, и
// сообщать серверу о пройденных уровнях.

import { api } from './api.js'

let signedIn = false

/** Вызывается сессией при входе и выходе. */
export const setSignedIn = (yes) => { signedIn = yes }

export const isSignedIn = () => signedIn

/**
 * Отметить пройденный уровень — если есть аккаунт и если известно, в каком
 * прохождении.
 *
 * Проверка на входе не формальность: без неё каждый пройденный уровень слал
 * запрос, который мог вернуть только 401, да ещё и с предварительным походом
 * за CSRF-кукой — два обращения, чтобы дважды услышать, что мы не вошли.
 *
 * Не бросает и не задерживает: уровень уже пройден, карта уже перерисована, и
 * сообщать игроку о неудаче здесь нечего.
 */
export function reportProgress(storyId, levelId, slotId = null) {
  if (!signedIn) return Promise.resolve(null)

  return api
    .post('/api/progress/complete', { storyId, levelId, slotId })
    .catch(() => null)
}
