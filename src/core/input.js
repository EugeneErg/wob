// Запись ввода игрока, привязанная к тикам.
//
// Главное требование: запись не должна зависеть от того, сколько кадров в
// секунду было у игрока. Поэтому ввод не хранится «во столько-то миллисекунд»
// — он хранится в тике номер N. Тик всегда одной длины (clock.js), так что
// запись, сделанная на 144 Гц, воспроизводится на 30 Гц в те же моменты
// игрового времени, шаг в шаг.
//
// Координаты пишутся мировые, а не экранные. Экранные зависят от размера окна
// и от того, куда игрок отмотал камеру; мировые — нет. Камера вообще не влияет
// на симуляцию, поэтому в запись не попадает.
//
// Числа округляются при записи, и в мир уходит уже округлённое значение —
// иначе живой прогон шёл бы по точным координатам, а повтор по округлённым,
// и они разъезжались бы через сотню тиков.

export const DOWN = 0
export const MOVE = 1
export const UP = 2
export const HOVER = 3

// Тысячная доля пикселя мира: мельче человек не целится, а размер записи
// это заметно сокращает.
const Q = 1000
const q = (v) => Math.round(v * Q) / Q

// Одно событие — плоская четвёрка [tick, kind, x, y]. Плоский массив вместо
// массива объектов: запись длинного прохождения — это десятки тысяч событий,
// и {tick,kind,x,y} на каждое раздувает JSON втрое.
export class InputLog {
  constructor(events = []) {
    this.events = events            // подряд: tick, kind, x, y, tick, kind, ...
    this._cursor = 0                // позиция чтения при воспроизведении
  }

  get length() { return this.events.length / 4 }

  // --- запись ---------------------------------------------------------------
  // Возвращает то, что записано: вызывающая сторона обязана отдать в мир
  // именно это, а не исходную точку.
  record(tick, kind, pt) {
    const x = q(pt?.x ?? 0)
    const y = q(pt?.y ?? 0)
    this.events.push(tick, kind, x, y)
    return { x, y }
  }

  // --- воспроизведение ------------------------------------------------------
  // Все события данного тика, по порядку. Курсор идёт только вперёд, поэтому
  // проигрывание всей записи — линейное, без поиска по массиву.
  at(tick) {
    const out = []
    const e = this.events
    while (this._cursor < e.length && e[this._cursor] === tick) {
      out.push({ kind: e[this._cursor + 1], x: e[this._cursor + 2], y: e[this._cursor + 3] })
      this._cursor += 4
    }
    return out
  }

  // Есть ли ещё что играть. По этому признаку видно, что запись доиграна,
  // даже если уровень не был пройден (игрок бросил попытку).
  get done() { return this._cursor >= this.events.length }

  // Номер тика последнего события — сколько тиков всего нужно проиграть,
  // чтобы показать всё, что делал игрок.
  get lastTick() { return this.events.length ? this.events[this.events.length - 4] : 0 }

  rewind() { this._cursor = 0 }

  // Обрезать запись по тик включительно. Нужно живой игре при откате: всё,
  // что игрок наделал после этого тика, он переигрывает заново, и в записи
  // остаться не должно — иначе повтор пошёл бы по двум вводам сразу.
  // Сколько событий выброшено, возвращается: выброшенное — не «ничего», и
  // тот, кто откатывает, обязан это где-то учесть.
  truncate(tick) {
    const e = this.events
    let n = e.length
    while (n >= 4 && e[n - 4] > tick) n -= 4
    const dropped = (e.length - n) / 4
    e.length = n
    this._cursor = Math.min(this._cursor, n)
    return dropped
  }

  toJSON() { return this.events }
  static from(events) { return new InputLog(Array.isArray(events) ? events.slice() : []) }
}

// Отдать событие миру. Одна точка перевода «что записано» → «что вызвать»,
// общая для живой игры и для повтора: если бы живой ввод шёл в мир напрямую,
// а повтор через эту функцию, любое расхождение между ними стало бы багом,
// который видно только в реплее.
export function applyEvent(world, ev) {
  const pt = { x: ev.x, y: ev.y }
  if (ev.kind === DOWN) world.pointerDown(pt)
  else if (ev.kind === MOVE) world.pointerMove(pt)
  else if (ev.kind === UP) world.pointerUp(pt)
  else if (ev.kind === HOVER) world.pointerHover(pt)
}
