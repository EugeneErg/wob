// Проверки, которые умеют не пройти.
//
// До этого тесты печатали «true» или «ПЛОХО» и всё равно завершались успешно:
// прогон ловил исключение, писал строку и шёл дальше, а код выхода всегда был
// нулевой. То есть шесть десятков файлов проверок были заметками, а не
// защитой — в сборке они не поймали бы ничего.
//
// Здесь минимум, который это чинит: check() запоминает провалы и в конце
// процесса выставляет ненулевой код выхода. Ничего больше не требуется —
// прогон уже смотрит на код выхода каждого файла.

let failed = 0
let total = 0

export function check(name, cond, detail = '') {
  total++
  if (cond) {
    console.log(`  ок    ${name}${detail ? ` — ${detail}` : ''}`)
    return true
  }
  failed++
  console.log(`  ПЛОХО ${name}${detail ? ` — ${detail}` : ''}`)
  return false
}

// Числа с плавающей точкой не сравнивают на равенство: у симуляции всегда
// есть шум последнего бита.
export const near = (name, got, want, tol = 1e-6) =>
  check(name, Math.abs(got - want) <= tol, `получили ${got}, ждали ${want}`)

export const equal = (name, got, want) =>
  check(name, got === want, got === want ? '' : `получили ${got}, ждали ${want}`)

// Вызывается автоматически при завершении: если хоть одна проверка не прошла,
// процесс завершается с ошибкой и прогон это увидит.
process.on('exit', () => {
  if (!total) return
  if (failed) {
    console.log(`  ── провалено ${failed} из ${total}`)
    process.exitCode = 1
  }
})
