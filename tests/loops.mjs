// История не должна замыкаться в кольцо.
//
// Кольцо не портит вид карты — оно запирает содержимое. Точка открывается,
// когда пройден хоть один ведущий в неё родитель (nodeOpen); у каждой точки
// кольца родитель есть, и ни один не проходим. Кольцо и всё, что растёт за
// ним, остаётся недостижимым навсегда, при том что история сохраняется и
// рисуется как ни в чём не бывало — то есть само по себе это не заметно.
//
// Тот же вопрос задаёт сервер перед записью. Здесь он задаётся раньше, чтобы
// автор не смог нарисовать заведомо мёртвую линию.

import { check } from './assert.mjs'

const store = new Map()
globalThis.localStorage = {
  get length() { return store.size },
  key: (i) => [...store.keys()][i],
  getItem: (k) => (store.has(k) ? store.get(k) : null),
  setItem: (k, v) => store.set(k, String(v)),
  removeItem: (k) => store.delete(k),
}

const { createServer } = await import('vite')
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' })
const lib = await server.ssrLoadModule('/src/core/library.js')

// Две главы, потому что связь свободно уходит на соседнюю карту: кольцо
// складывается из двух глав, в каждой из которых по отдельности всё честно.
lib.hydrateLibrary({
  format: 'goo-bundle',
  stories: [{ id: 'st', title: 'S', cover: '#000', chapters: ['ch-a', 'ch-b'], hot: [] }],
  chapters: [
    {
      id: 'ch-a',
      title: 'A',
      nodes: [
        { id: 'a1', levelId: 'l1', x: 10, y: 50, next: ['a2'] },
        { id: 'a2', levelId: 'l2', x: 30, y: 50, next: ['b1'] },
        // Тупик в первой главе: из него никуда не ведёт, поэтому связь в него
        // кольца не образует — и на нём видно, что второй заход в главу это
        // отдельная беда, а не частный случай кольца.
        { id: 'a3', levelId: 'l5', x: 50, y: 50, next: [] },
      ],
      hot: [],
    },
    {
      id: 'ch-b',
      title: 'B',
      nodes: [
        { id: 'b1', levelId: 'l3', x: 10, y: 50, next: ['b2'] },
        { id: 'b2', levelId: 'l4', x: 30, y: 50, next: [] },
      ],
      hot: [],
    },
  ],
  levels: [
    { id: 'l1', name: '1', hot: [] }, { id: 'l2', name: '2', hot: [] },
    { id: 'l3', name: '3', hot: [] }, { id: 'l4', name: '4', hot: [] },
    { id: 'l5', name: '5', hot: [] },
  ],
  assets: [],
})

// Короткая дорога вперёд в обход середины: a2 и так доходит до b2 через b1,
// вторая связь напрямую ничего не замыкает.
check('дорога вперёд в обход середины разрешена', !lib.wouldCycle('a2', 'b2'))

check('связь в саму себя — кольцо', lib.wouldCycle('a1', 'a1'))
check('короткое кольцо назад — кольцо', lib.wouldCycle('a2', 'a1'))
check('длинное кольцо через главу — кольцо', lib.wouldCycle('b2', 'a1'))
check('кольцо через границу глав — кольцо', lib.wouldCycle('b1', 'a2'))

// Слияние веток кольцом не является: точка откроется по любому из пройденных
// родителей, поэтому две дороги в одну точку — законное содержимое.
check('слияние двух дорог в одну точку разрешено', !lib.wouldCycle('a1', 'b2'))

// Ветвление вперёд тоже.
check('развилка вперёд разрешена', !lib.wouldCycle('a1', 'b1'))

// Точка, ни с чем не связанная, ничему не мешает.
check('связь с новой точкой разрешена', !lib.wouldCycle('b2', 'нет-такой'))

// --- второй заход в главу ----------------------------------------------------
//
// Кольцом это не является: по точкам дорога идёт строго вперёд и нигде не
// смыкается. Но глава при этом перестаёт быть отрезком пути и становится двумя
// разными местами под одним именем, а весь учёт хода игры ведётся по главам.
// Поэтому правило отдельное, и проверка колец такое пропускает.

// a1 → a2 → b1 → b2, и a3 стоит в первой главе тупиком.
//
// Связь b2 → a3 никакого кольца не образует: из a3 обратно к b2 хода нет,
// дорога по точкам идёт строго вперёд. Но путь при этом выходит из первой
// главы и возвращается в неё — ровно то, что проверка колец пропускает.
check('такая связь кольца не образует', !lib.wouldCycle('b2', 'a3'))
check('но возврат в покинутую главу всё равно запрещён', lib.wouldRevisitChapter('b2', 'a3'))

// Внутри главы ходить можно сколько угодно.
check('связь внутри главы разрешена', !lib.wouldRevisitChapter('a1', 'a2'))
check('и вторая связь внутри той же главы тоже', !lib.wouldRevisitChapter('b1', 'b2'))

// Идти дальше вперёд — законный путь, а не возврат.
check('переход в следующую главу разрешён', !lib.wouldRevisitChapter('a1', 'b2'))

console.log('точек в разборе: 5, глав: 2')

await server.close()
