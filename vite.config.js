import { defineConfig } from 'vite'
import vue from '@vitejs/plugin-vue'

// Прокси на бэкенд — не для удобства, а по необходимости.
//
// Сессия живёт в куке, а кука ходит только между своими. Если фронт на :5173
// стучится напрямую на :8000, браузер считает это чужим сайтом: кука не
// прилетает, CSRF не сходится, вход выглядит сломанным без единой ошибки в
// консоли. С прокси всё уходит на :5173 и остаётся одним источником.
//
// В продакшене ту же роль играет обычный веб-сервер: статика игры и /api с
// одного домена.

export default defineConfig({
  plugins: [vue()],
  base: './',
  server: {
    proxy: {
      '/api': { target: 'http://127.0.0.1:8000', changeOrigin: true },
      '/sanctum': { target: 'http://127.0.0.1:8000', changeOrigin: true },
    },
  },
})
