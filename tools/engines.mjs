// Реестр движков: какая версия правил каким кодом проигрывается.
//
// Запись хранит две версии — содержимого и правил, — и вторая существует ровно
// затем, чтобы старый прогон можно было пересчитать так, как он игрался. Пока
// верификатор умел только текущую физику, «другая версия правил» означала
// отказ, и это было неверно: запись не становится подделкой оттого, что мы
// поправили решатель. Она становится записью на другой физике, и проверять её
// надо на ней.
//
// Отсюда порядок, которому придётся следовать при каждой правке физики:
//
//   1. заморозить нынешний src/core в engines/vN/ (копией, а не ссылкой);
//   2. поднять RULES_VERSION;
//   3. дописать сюда строчку с новой версией.
//
// Копией, а не ссылкой на git-историю, потому что проверка обязана работать в
// собранном контейнере, где никакого git нет. Дублирование кода здесь — не
// небрежность, а условие: замороженный движок и не должен меняться, иначе он
// перестанет быть тем, на чём игрались старые записи.

import { RULES_VERSION } from '../src/core/releases.js'

/**
 * Загрузчики по версии правил.
 *
 * Текущая версия указывает на живой src/core — отдельной копии для неё нет и
 * быть не должно: пока версия не заморожена, единственный её носитель это код,
 * который сейчас в игре.
 */
const engines = {
  [RULES_VERSION]: () => import('../src/core/run.js'),

  // По мере заморозки:
  // 1: () => import('./engines/v1/run.js'),
}

export const knownVersions = () => Object.keys(engines).map(Number).sort((a, b) => a - b)

export const currentVersion = RULES_VERSION

/**
 * Достать движок нужной версии.
 *
 * Возвращает null, если такой версии у нас нет. Отличать «нет движка» от
 * «прогон плохой» обязательно: в первом случае запись нельзя ни зачесть, ни
 * отвергнуть — её просто некому проверить, и удалять её за это было бы
 * наказанием за наш недосмотр.
 */
export async function engineFor(rulesVersion) {
  const load = engines[Number(rulesVersion)]

  if (!load) return null

  const mod = await load()

  return { Run: mod.Run, REPLAY: mod.REPLAY }
}
