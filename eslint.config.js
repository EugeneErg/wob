// Статическая проверка — то, чего не умеет ни один прогон в tests/.
//
// Сюита проверяет физику числами и экраны SSR-рендером. Ни то, ни другое не
// видит имени, которого нет: `pushMap` вызывался из пяти мест и не был объявлен
// нигде, `storyId` — из трёх. Оба падали с ReferenceError у автора с аккаунтом,
// оба прожили в репозитории месяцами, и оба нашлись разбором глазами, а не
// прогоном. Это ровно то, что линтер ловит бесплатно.
//
// Правил здесь намеренно мало. Цель не «привести код к стилю» — стиль тут свой
// и осмысленный, — а поймать сломанное. Всё, что спорно или косметично,
// выключено: правило, которое приходится глушить комментариями, быстро учат
// игнорировать целиком, и тогда оно не ловит и настоящее.

import js from '@eslint/js'
import vue from 'eslint-plugin-vue'
import globals from 'globals'

export default [
  {
    ignores: ['dist/**', 'node_modules/**'],
  },

  js.configs.recommended,
  ...vue.configs['flat/recommended'],

  {
    languageOptions: {
      ecmaVersion: 2023,
      sourceType: 'module',
      globals: {
        ...globals.browser,
        ...globals.node,
      },
    },

    rules: {
      // Главное правило этого файла: имя, которого нет.
      'no-undef': 'error',

      // Объявили и не используете — обычно остаток от правки. Аргументы
      // функций исключены: сигнатуру часто держат ради читаемости, а
      // переименовывать их в _ ради линтера значит портить код ради линтера.
      'no-unused-vars': ['error', {
        args: 'none',
        caughtErrors: 'none',
        varsIgnorePattern: '^_',
      }],

      // Здесь много осмысленно пустых блоков: «полка подождёт», «файл не
      // выбран». Пустой catch — приём, а не недосмотр.
      'no-empty': ['error', { allowEmptyCatch: true }],

      // `let out = ''`, а дальше присваивание в обеих ветках try/catch.
      // Формально начальное значение не читается, но убрать его — значит
      // объявить переменную без значения и полагаться на то, что одна из веток
      // точно сработает. Правило спорит с читаемостью, а не с ошибкой.
      'no-useless-assignment': 'off',

      // Timeline, WorldCanvas — имена по одному слову, и это нормально: они
      // не конкурируют с HTML-тегами, потому что здесь нет глобальной
      // регистрации компонентов.
      'vue/multi-word-component-names': 'off',

      // Разметка форматируется руками и читаемо; спорить с ней линтеру незачем.
      'vue/max-attributes-per-line': 'off',
      'vue/singleline-html-element-content-newline': 'off',
      'vue/html-self-closing': 'off',
      'vue/html-indent': 'off',
      'vue/html-closing-bracket-newline': 'off',
      'vue/attributes-order': 'off',
      'vue/first-attribute-linebreak': 'off',
      'vue/multiline-html-element-content-newline': 'off',

      // v-html здесь — иконки сущностей: SVG из собственного реестра, не из
      // пользовательского ввода. Правило право в общем случае и не право тут,
      // а глушить его комментарием в каждой из трёх точек шумнее, чем сказать
      // один раз здесь.
      'vue/no-v-html': 'off',

      // Необязательный проп без значения по умолчанию — осознанно: undefined и
      // есть «не передали», и подставлять вместо него пустую строку значит
      // терять это различие.
      'vue/require-default-prop': 'off',
    },
  },

  {
    // Проверки поднимают себе окружение сами и подменяют localStorage.
    files: ['tests/**/*.mjs'],
    languageOptions: { globals: { ...globals.node } },
  },
]
